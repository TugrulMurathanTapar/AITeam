"""Multi-AI Deliberation Engine for Multi-AI Orchestrator.

Implements a parallel-then-synthesize consensus architecture where multiple
AI models are queried concurrently on user inputs, and a designated judge model
synthesizes a final, unified, optimal answer combining the best insights.
"""

from __future__ import annotations

import asyncio
from dataclasses import dataclass, field
from datetime import datetime
import logging
import time
from typing import Any, AsyncIterator, Callable, Dict, List, Optional

from core.api_handler import AIProvider, APIClient
from ui.i18n import I18n

logger = logging.getLogger("orchestrator.deliberation")


@dataclass
class DeliberationResponse:
    """Individual model response produced during the parallel deliberation phase.

    Attributes:
        provider_id: Unique identifier of the provider.
        model_name: Display name of the model.
        content: Textual response generated by the model.
        latency_ms: Round-trip response time in milliseconds.
        token_usage: Dictionary of token consumption statistics.
        error: Error message string if the provider query failed.
    """

    provider_id: str
    model_name: str
    content: str
    latency_ms: float
    token_usage: dict = field(default_factory=dict)
    error: str | None = None

    def to_dict(self) -> dict[str, Any]:
        """Convert DeliberationResponse to dictionary representation."""
        return {
            "provider_id": self.provider_id,
            "model_name": self.model_name,
            "content": self.content,
            "latency_ms": self.latency_ms,
            "token_usage": self.token_usage,
            "error": self.error,
        }


@dataclass
class DeliberationResult:
    """Consolidated outcome of a multi-model deliberation and synthesis session.

    Attributes:
        responses: List of individual provider responses from Phase 1.
        synthesis: Final synthesized answer from the judge model (or sole model).
        judge_model: Name of the model that synthesized the consensus.
        total_time_ms: Total duration of the deliberation process in milliseconds.
        consensus_achieved: True if at least one model succeeded and synthesis completed.
    """

    responses: list[DeliberationResponse]
    synthesis: str
    judge_model: str
    total_time_ms: float
    consensus_achieved: bool

    def to_dict(self) -> dict[str, Any]:
        """Convert DeliberationResult to dictionary representation."""
        return {
            "responses": [r.to_dict() for r in self.responses],
            "synthesis": self.synthesis,
            "judge_model": self.judge_model,
            "total_time_ms": self.total_time_ms,
            "consensus_achieved": self.consensus_achieved,
        }


class DeliberationEngine:
    """Multi-AI debate and consensus engine implementing parallel-then-synthesize.

    Phase 1 (Parallel Querying): Concurrently sends the prompt to all active
    AI providers. Each model responds independently in complete isolation.

    Phase 2 (Consensus Synthesis): Feeds all valid responses into a meta-prompt
    evaluated by a designated judge model, which reconciles discrepancies and
    synthesizes a high-accuracy, authoritative response.
    """

    def __init__(self, api_client: APIClient) -> None:
        """Initialize the DeliberationEngine.

        Args:
            api_client: Instantiated APIClient used for dispatching queries.
        """
        self._api_client: APIClient = api_client
        self._event_callback: Callable[..., Any] | None = None
        self._timeout: float = 120.0  # Default parallel timeout in seconds
        self._judge_provider_id: str | None = None
        # Token limits for deliberation (user-configurable)
        self._deliberation_max_tokens: int = 1000   # Phase 1: each model's response
        self._synthesis_max_tokens: int = 2000       # Phase 2: judge synthesis

    def set_event_callback(self, callback: Callable[..., Any]) -> None:
        """Register callback for real-time deliberation lifecycle events.

        The callback may be a synchronous function or a coroutine taking
        `(event_type: str, data: dict)`.

        Args:
            callback: Callable receiving event type and event data payload.
        """
        self._event_callback = callback

    def set_timeout(self, seconds: float) -> None:
        """Set maximum timeout in seconds for parallel model queries.

        Args:
            seconds: Timeout duration in seconds (positive float).
        """
        self._timeout = max(1.0, float(seconds))
        logger.debug("Deliberation parallel timeout set to %.1f seconds", self._timeout)

    def set_judge(self, provider_id: str | None) -> None:
        """Designate the primary judge provider by ID or model identifier.

        Args:
            provider_id: Provider ID or model identifier string, or None for auto.
        """
        self._judge_provider_id = provider_id
        logger.debug("Deliberation judge provider set to: %s", provider_id)

    def set_max_tokens(self, deliberation_tokens: int, synthesis_tokens: int | None = None) -> None:
        """Configure token limits for deliberation phases.

        Args:
            deliberation_tokens: Max tokens per model in Phase 1 (parallel queries).
            synthesis_tokens: Max tokens for judge synthesis in Phase 2.
                              Defaults to 2x deliberation_tokens if not specified.
        """
        self._deliberation_max_tokens = max(100, int(deliberation_tokens))
        self._synthesis_max_tokens = int(synthesis_tokens) if synthesis_tokens else self._deliberation_max_tokens * 2
        logger.debug(
            "Deliberation token limits: phase1=%d, synthesis=%d",
            self._deliberation_max_tokens, self._synthesis_max_tokens,
        )

    async def deliberate(
        self,
        messages: list[dict],
        system_prompt: str,
        providers: list[AIProvider],
    ) -> DeliberationResult:
        """Execute parallel-then-synthesize multi-model deliberation.

        Queries all provided AI models concurrently, evaluates their answers,
        and prompts the judge model to synthesize the final unified response.

        Args:
            messages: List of chat message dictionaries in standard schema.
            system_prompt: Base system prompt instructions.
            providers: List of enabled AIProvider configurations.

        Returns:
            DeliberationResult containing all model outputs and the synthesized verdict.
        """
        start_time = time.perf_counter()

        if not providers:
            total_time = (time.perf_counter() - start_time) * 1000.0
            return DeliberationResult(
                responses=[],
                synthesis="No active providers available for deliberation.",
                judge_model="none",
                total_time_ms=round(total_time, 2),
                consensus_achieved=False,
            )

        # Emit deliberation_start event
        await self._emit_event(
            "deliberation_start",
            {
                "models": [p.name for p in providers],
                "count": len(providers),
                "timestamp": datetime.now().isoformat(),
            },
        )

        # Phase 1: Parallel model queries
        tasks = [
            self._query_provider(provider, messages, system_prompt)
            for provider in providers
        ]

        try:
            results = await asyncio.wait_for(
                asyncio.gather(*tasks, return_exceptions=True),
                timeout=self._timeout,
            )
        except asyncio.TimeoutError:
            logger.warning("Deliberation parallel query timed out after %.1fs", self._timeout)
            results = [
                TimeoutError(f"Model query exceeded timeout threshold of {self._timeout}s")
                for _ in providers
            ]

        # Process individual provider outcomes
        responses: list[DeliberationResponse] = []
        for provider, result in zip(providers, results):
            if isinstance(result, Exception):
                response = DeliberationResponse(
                    provider_id=provider.id,
                    model_name=provider.name,
                    content="",
                    latency_ms=0.0,
                    error=str(result),
                )
            else:
                response = result

            responses.append(response)
            preview_content = (
                response.content[:200] + "..."
                if len(response.content) > 200
                else response.content
            )
            await self._emit_event(
                "deliberation_response",
                {
                    "provider_id": provider.id,
                    "model": provider.name,
                    "content": preview_content,
                    "latency_ms": response.latency_ms,
                    "error": response.error,
                },
            )

        # Filter successful responses
        successful = [r for r in responses if r.error is None and r.content.strip()]

        if not successful:
            total_time = (time.perf_counter() - start_time) * 1000.0
            logger.error("Deliberation failed: All %d models failed to respond.", len(providers))
            await self._emit_event(
                "deliberation_end",
                {
                    "total_time_ms": round(total_time, 2),
                    "models_responded": 0,
                    "models_failed": len(responses),
                    "consensus_achieved": False,
                },
            )
            return DeliberationResult(
                responses=responses,
                synthesis="All models failed to respond or encountered errors.",
                judge_model="none",
                total_time_ms=round(total_time, 2),
                consensus_achieved=False,
            )

        # If only one response succeeded, bypass synthesis and return directly
        if len(successful) == 1:
            total_time = (time.perf_counter() - start_time) * 1000.0
            single = successful[0]
            logger.info("Deliberation completed with single valid response from %s", single.model_name)
            await self._emit_event(
                "deliberation_end",
                {
                    "total_time_ms": round(total_time, 2),
                    "models_responded": 1,
                    "models_failed": len(responses) - 1,
                    "consensus_achieved": True,
                },
            )
            return DeliberationResult(
                responses=responses,
                synthesis=single.content,
                judge_model=single.model_name,
                total_time_ms=round(total_time, 2),
                consensus_achieved=True,
            )

        # Phase 2: Synthesis by designated judge model
        judge = self._get_judge(providers)
        await self._emit_event(
            "deliberation_synthesis",
            {
                "judge": judge.name,
                "judge_model_id": judge.model_id,
                "candidate_count": len(successful),
            },
        )

        synthesis_prompt = self._build_synthesis_prompt(messages, successful)

        try:
            synthesis_response = await self._api_client.chat_completion(
                provider=judge,
                messages=[{"role": "user", "content": synthesis_prompt}],
                system_prompt=self._get_judge_system_prompt(),
                max_tokens=self._synthesis_max_tokens,
            )
            synthesis_text = synthesis_response.get("content", "")
        except Exception as judge_err:
            logger.error("Judge model synthesis failed with %s: %s", judge.name, judge_err)
            # Fallback to the first successful candidate's response
            synthesis_text = (
                f"[Synthesis failed due to judge error: {judge_err}]\n\n"
                f"Selected best answer from {successful[0].model_name}:\n\n"
                f"{successful[0].content}"
            )

        total_time = (time.perf_counter() - start_time) * 1000.0

        await self._emit_event(
            "deliberation_end",
            {
                "total_time_ms": round(total_time, 2),
                "models_responded": len(successful),
                "models_failed": len(responses) - len(successful),
                "judge": judge.name,
                "consensus_achieved": True,
            },
        )

        return DeliberationResult(
            responses=responses,
            synthesis=synthesis_text,
            judge_model=judge.name,
            total_time_ms=round(total_time, 2),
            consensus_achieved=True,
        )

    async def deliberate_stream(
        self,
        messages: list[dict],
        system_prompt: str,
        providers: list[AIProvider],
    ) -> AsyncIterator[str]:
        """Streaming deliberation — runs Phase 1 parallel queries, then streams synthesis.

        Phase 1 collects candidate answers in parallel, then Phase 2 streams tokens
        from the judge model as the synthesized consensus is generated.

        Args:
            messages: List of chat messages in standard schema.
            system_prompt: Base system prompt instructions.
            providers: List of enabled AIProvider configurations.

        Yields:
            Token chunks emitted by the judge model's synthesis stream.
        """
        start_time = time.perf_counter()

        if not providers:
            yield "No active providers available for deliberation."
            return

        # Emit deliberation_start event
        await self._emit_event(
            "deliberation_start",
            {
                "models": [p.name for p in providers],
                "count": len(providers),
                "timestamp": datetime.now().isoformat(),
            },
        )

        # Phase 1: Parallel model queries
        tasks = [
            self._query_provider(provider, messages, system_prompt)
            for provider in providers
        ]

        try:
            results = await asyncio.wait_for(
                asyncio.gather(*tasks, return_exceptions=True),
                timeout=self._timeout,
            )
        except asyncio.TimeoutError:
            logger.warning("Deliberation stream parallel query timed out after %.1fs", self._timeout)
            results = [
                TimeoutError(f"Model query exceeded timeout threshold of {self._timeout}s")
                for _ in providers
            ]

        # Process individual provider outcomes
        responses: list[DeliberationResponse] = []
        for provider, result in zip(providers, results):
            if isinstance(result, Exception):
                response = DeliberationResponse(
                    provider_id=provider.id,
                    model_name=provider.name,
                    content="",
                    latency_ms=0.0,
                    error=str(result),
                )
            else:
                response = result

            responses.append(response)
            preview_content = (
                response.content[:200] + "..."
                if len(response.content) > 200
                else response.content
            )
            await self._emit_event(
                "deliberation_response",
                {
                    "provider_id": provider.id,
                    "model": provider.name,
                    "content": preview_content,
                    "latency_ms": response.latency_ms,
                    "error": response.error,
                },
            )

        # Filter successful responses
        successful = [r for r in responses if r.error is None and r.content.strip()]

        if not successful:
            total_time = (time.perf_counter() - start_time) * 1000.0
            error_message = "All models failed to respond or encountered errors."
            await self._emit_event(
                "deliberation_end",
                {
                    "total_time_ms": round(total_time, 2),
                    "models_responded": 0,
                    "models_failed": len(responses),
                    "consensus_achieved": False,
                },
            )
            yield error_message
            return

        # If only one response succeeded, yield it directly without synthesis
        if len(successful) == 1:
            total_time = (time.perf_counter() - start_time) * 1000.0
            single = successful[0]
            await self._emit_event(
                "deliberation_end",
                {
                    "total_time_ms": round(total_time, 2),
                    "models_responded": 1,
                    "models_failed": len(responses) - 1,
                    "consensus_achieved": True,
                },
            )
            yield single.content
            return

        # Phase 2: Stream judge synthesis
        judge = self._get_judge(providers)
        await self._emit_event(
            "deliberation_synthesis",
            {
                "judge": judge.name,
                "judge_model_id": judge.model_id,
                "candidate_count": len(successful),
            },
        )

        synthesis_prompt = self._build_synthesis_prompt(messages, successful)

        try:
            async for chunk in self._api_client.chat_completion_stream(
                provider=judge,
                messages=[{"role": "user", "content": synthesis_prompt}],
                system_prompt=self._get_judge_system_prompt(),
                max_tokens=self._synthesis_max_tokens,
            ):
                yield chunk
        except Exception as judge_err:
            logger.error("Judge streaming synthesis error with %s: %s", judge.name, judge_err)
            fallback_text = (
                f"\n\n[Judge streaming synthesis interrupted: {judge_err}]\n"
                f"Consensus from {successful[0].model_name}:\n\n"
                f"{successful[0].content}"
            )
            yield fallback_text

        total_time = (time.perf_counter() - start_time) * 1000.0
        await self._emit_event(
            "deliberation_end",
            {
                "total_time_ms": round(total_time, 2),
                "models_responded": len(successful),
                "models_failed": len(responses) - len(successful),
                "judge": judge.name,
                "consensus_achieved": True,
            },
        )

    async def _query_provider(
        self,
        provider: AIProvider,
        messages: list[dict],
        system_prompt: str,
    ) -> DeliberationResponse:
        """Query a single provider and construct a DeliberationResponse.

        Args:
            provider: Target AIProvider configuration.
            messages: List of chat messages in standard schema.
            system_prompt: System prompt instructions.

        Returns:
            DeliberationResponse containing content or error and latency metrics.
        """
        start = time.perf_counter()
        try:
            result = await self._api_client.chat_completion(
                provider=provider,
                messages=messages,
                system_prompt=self._get_deliberation_system_prompt(system_prompt),
                max_tokens=self._deliberation_max_tokens,
            )
            latency = (time.perf_counter() - start) * 1000.0
            return DeliberationResponse(
                provider_id=provider.id,
                model_name=provider.name,
                content=result.get("content", ""),
                latency_ms=round(latency, 2),
                token_usage=result.get("usage", {}),
            )
        except Exception as exc:
            latency = (time.perf_counter() - start) * 1000.0
            logger.warning("Deliberation query error for provider '%s': %s", provider.name, exc)
            return DeliberationResponse(
                provider_id=provider.id,
                model_name=provider.name,
                content="",
                latency_ms=round(latency, 2),
                error=str(exc),
            )

    def _get_judge(self, providers: list[AIProvider]) -> AIProvider:
        """Select the judge model from available providers.

        If a specific judge provider ID or model name has been configured,
        matches against it. Otherwise defaults to the first available provider.

        Args:
            providers: List of enabled AIProvider candidates.

        Returns:
            Selected AIProvider to serve as judge.

        Raises:
            ValueError: If providers list is empty.
        """
        if not providers:
            raise ValueError("No providers available for judge selection.")

        if self._judge_provider_id:
            for p in providers:
                if (
                    p.id == self._judge_provider_id
                    or p.name.lower() == self._judge_provider_id.lower()
                    or p.model_id.lower() == self._judge_provider_id.lower()
                ):
                    return p

        return providers[0]

    def _build_synthesis_prompt(
        self,
        original_messages: list[dict],
        responses: list[DeliberationResponse],
    ) -> str:
        """Build the synthesis prompt asking the judge to combine all responses with token windowing & clipping.

        Args:
            original_messages: The full chat message history up to this turn.
            responses: List of successful DeliberationResponse objects.

        Returns:
            Formatted synthesis meta-prompt string.
        """
        # Token optimization: window conversation to last 6 messages
        windowed_messages = original_messages[-6:] if len(original_messages) > 6 else original_messages

        # Format conversation context
        conversation_lines: list[str] = []
        for msg in windowed_messages:
            role = str(msg.get("role", "user")).capitalize()
            content = str(msg.get("content", "")).strip()
            if content:
                conversation_lines.append(f"{role}: {content}")

        conversation_text = (
            "\n".join(conversation_lines)
            if conversation_lines
            else "(No prior conversation messages)"
        )

        # Format candidate responses with clipping (max 1200 chars each for token efficiency)
        candidate_blocks: list[str] = []
        for idx, resp in enumerate(responses, start=1):
            content_snippet = resp.content.strip()
            if len(content_snippet) > 1200:
                content_snippet = content_snippet[:1200] + "\n[... clipped for token efficiency ...]"
            block = (
                f"### Candidate Model {idx} ({resp.model_name}):\n"
                f"{content_snippet}\n"
            )
            candidate_blocks.append(block)

        candidates_text = "\n".join(candidate_blocks)

        return (
            f"User Conversation & Query (Optimized Window):\n"
            f"--------------------------------------------------\n"
            f"{conversation_text}\n"
            f"--------------------------------------------------\n\n"
            f"Independent Model Responses to Synthesize:\n"
            f"==================================================\n"
            f"{candidates_text}\n"
            f"==================================================\n\n"
            f"Synthesis Instructions for Judge AI:\n"
            f"1. Thoroughly review and contrast each candidate response for factual correctness, logical coherence, and completeness.\n"
            f"2. Resolve any disagreements or discrepancies by selecting the most accurate and well-reasoned facts.\n"
            f"3. Combine the distinct strengths, examples, and nuances from each model into a single, comprehensive, and definitive response.\n"
            f"4. Do NOT reference 'Candidate 1', 'Model A', or the models by name in your output. Present your response seamlessly as a unified, direct answer to the user.\n"
            f"5. Maintain clear structure, formatting (markdown), and appropriate technical depth."
        )

    def _get_deliberation_system_prompt(self, base_prompt: str) -> str:
        """Build a concise deliberation system prompt wrapping the base prompt.

        Instructs models to respond briefly during Phase 1 to minimize tokens.
        The synthesis judge handles combining responses into the final answer.

        Args:
            base_prompt: The user/orchestrator base system prompt.

        Returns:
            Enhanced system prompt with token-saving instructions.
        """
        efficiency_note = (
            f"\n\n[DELIBERATION MODE] You are one of multiple AI models responding to this "
            f"query in parallel. Your response will be combined with other models' answers "
            f"by a synthesis judge. Be concise and direct — focus on accuracy over length. "
            f"Aim for {self._deliberation_max_tokens // 4} words or fewer. "
            f"Do not explain that you are in deliberation mode."
        )
        return (base_prompt + efficiency_note) if base_prompt else efficiency_note.strip()

    def _get_judge_system_prompt(self) -> str:
        """System prompt instructions for the judge AI model.

        Returns:
            Judge system prompt instruction string.
        """
        language_instruction = (
            "Son yanıtı tutarlı biçimde Türkçe ver; teknik terimler gerektiğinde İngilizce kalabilir."
            if I18n().current_language == "tr"
            else "Respond in the language of the user's request. Default to English if ambiguous."
        )
        return (
            "You are a Judge AI synthesizing responses from multiple AI models. "
            "Analyze each model's response for accuracy, completeness, and quality. "
            "Produce a single, unified, optimal answer that combines the best insights "
            "from all responses. If models disagree, evaluate the evidence and choose "
            "the most correct position. Do not mention the individual models by name "
            "in your final answer — present it as a single cohesive response. "
            + language_instruction
        )

    async def _emit_event(self, event_type: str, data: dict) -> None:
        """Emit real-time deliberation event to registered callback if present.

        Args:
            event_type: Identifier of the event.
            data: Payload dictionary describing event details.
        """
        if self._event_callback is not None:
            try:
                if asyncio.iscoroutinefunction(self._event_callback):
                    await self._event_callback(event_type, data)
                else:
                    self._event_callback(event_type, data)
            except Exception as exc:
                logger.warning("Deliberation event callback failed for '%s': %s", event_type, exc)
